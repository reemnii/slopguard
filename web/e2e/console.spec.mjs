import { test, expect } from '@playwright/test';
test('dashboard, scan, filters, details, export and persistence', async ({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Workspace overview'})).toBeVisible();
  await page.screenshot({path:'qa/overview.png',fullPage:true});
  await page.getByRole('button',{name:'New scan',exact:true}).last().click();
  await page.getByRole('button',{name:'Scan dependencies',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Scan report',exact:true})).toBeVisible({timeout:15000});
  await expect(page.getByRole('button',{name:'requets',exact:true})).toBeVisible();
  await page.getByLabel('Filter by risk').selectOption('High');
  await expect(page.getByRole('button',{name:'requests',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'requets',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('90');
  await expect(page.getByRole('dialog')).toContainText('Did you mean?');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByText('How is risk calculated?',{exact:true}).click();
  await expect(page.getByText('Missing from registry',{exact:true})).toBeVisible();
  const download=page.waitForEvent('download');await page.getByRole('button',{name:'Export report'}).click();
  expect((await download).suggestedFilename()).toMatch(/slopguard.*json/);
  await page.screenshot({path:'qa/results.png',fullPage:true});
  await page.getByRole('button',{name:'Scan History',exact:true}).click();
  await expect(page.getByRole('button',{name:'Untitled / python snippet',exact:true})).toBeVisible();
  await page.reload();await page.getByRole('button',{name:'Scan History',exact:true}).click();
  await expect(page.getByRole('button',{name:'Untitled / python snippet',exact:true})).toBeVisible();
  expect(errors).toEqual([]);
});
test('uploads, unknown packages, empty states and experiment lab',async({page})=>{
  await page.goto('/');await page.getByRole('button',{name:'New scan',exact:true}).last().click();
  await page.getByLabel('Code to scan').fill('');
  await page.getByRole('button',{name:'Scan dependencies',exact:true}).click();
  await expect(page.getByRole('alert').filter({hasText:'Add some code'})).toBeVisible();
  await page.getByRole('button',{name:'Upload files',exact:true}).click();
  await page.locator('input[type=file]').setInputFiles([{name:'example.py',mimeType:'text/plain',buffer:Buffer.from('import requests\nimport unknown_fixture_pkg')}]);
  await expect(page.getByRole('button',{name:'Remove example.py'})).toBeVisible();
  await page.getByRole('button',{name:'Remove example.py'}).click();
  await expect(page.getByRole('button',{name:'Remove example.py'})).toHaveCount(0);
  await page.locator('input[type=file]').setInputFiles([{name:'example.py',mimeType:'text/plain',buffer:Buffer.from('import unknown_fixture_pkg')}]);
  await page.getByRole('button',{name:'Scan dependencies',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Scan report',exact:true})).toBeVisible({timeout:15000});
  await expect(page.locator('tbody')).toContainText('Unverified');
  await page.getByRole('button',{name:'Experiments',exact:true}).click();
  await page.getByRole('combobox',{name:'Provider',exact:true}).selectOption('Groq');
  await page.getByRole('button',{name:'Generate sample AI code'}).click();
  await expect(page.getByLabel('Generated code preview')).toHaveValue(/Simulated Groq response/);
  await page.getByRole('button',{name:'Scan generated code'}).click();
  await expect(page.getByRole('heading',{name:'Scan report',exact:true})).toBeVisible({timeout:15000});
});
